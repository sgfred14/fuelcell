import React, { memo } from "react";
import { AlertTriangle, CheckCircle, Info, Shield, Zap } from "lucide-react";
import type { EmsRecommendationItem } from "../../types";

interface AdvisoryListProps {
  advisories?: EmsRecommendationItem[];
}

export const AdvisoryList: React.FC<AdvisoryListProps> = memo(({ advisories = [] }) => {
  const items = Array.isArray(advisories) ? advisories : [];
  const getBadgeClass = (priority: string) => {
    switch (priority) {
      case "HIGH":
        return "badge badge-warn";
      case "MEDIUM":
        return "badge badge-info";
      case "LOW":
        return "badge";
      case "INFO":
      default:
        return "badge badge-ok";
    }
  };

  const getIcon = (category: string, priority?: string) => {
    if (priority === "HIGH") {
      return <AlertTriangle size={18} style={{ color: "#ef4444" }} aria-hidden="true" />;
    }
    switch (category) {
      case "Dispatch & Tariffs":
        return <Zap size={18} style={{ color: "#f59e0b" }} aria-hidden="true" />;
      case "Thermal Recovery":
        return <CheckCircle size={18} style={{ color: "#10b981" }} aria-hidden="true" />;
      case "Asset Longevity":
        return <Shield size={18} style={{ color: "#3b82f6" }} aria-hidden="true" />;
      case "Sustainability":
      default:
        return <Info size={18} style={{ color: "#8b5cf6" }} aria-hidden="true" />;
    }
  };

  return (
    <section className="card" aria-label="Operational Advisory Alerts">
      <div style={{ padding: "16px 20px", borderBottom: "1px solid var(--color-border)" }}>
        <h2 style={{ fontSize: 20 }}>Real-Time Operational Advisory Alerts</h2>
        <small className="fine">
          Prescriptive recommendations generated by AI predictive models to maximize efficiency and longevity.
        </small>
      </div>

      <div style={{ padding: 16, display: "flex", flexDirection: "column", gap: 12 }}>
        {items.map((adv) => (
          <div
            key={adv.id}
            style={{
              display: "flex",
              alignItems: "flex-start",
              gap: 14,
              padding: "12px 16px",
              background: "var(--color-surface-alt)",
              borderRadius: 6,
              border: "1px solid var(--color-border)",
            }}
          >
            <div style={{ marginTop: 2 }}>{getIcon(adv.category, adv.priority)}</div>
            <div style={{ flex: 1 }}>
              <div style={{ display: "flex", alignItems: "center", gap: 10, marginBottom: 4 }}>
                <span style={{ fontWeight: 600, fontSize: 14 }}>{adv.title}</span>
                <span className={getBadgeClass(adv.priority)} style={{ fontSize: 11 }}>
                  {adv.priority}
                </span>
                <span style={{ fontSize: 11, color: "var(--color-text-muted)" }}>{adv.category}</span>
              </div>
              <p style={{ margin: 0, fontSize: 13, color: "var(--color-text)", lineHeight: 1.4 }}>
                {adv.message}
              </p>
            </div>
          </div>
        ))}
      </div>
    </section>
  );
});

AdvisoryList.displayName = "AdvisoryList";
